int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int testCount;
    if (!(cin >> testCount))
        return 0;

    cout << testCount << '\n';
    cout << fixed << setprecision(3);
    for (int test = 0; test < testCount; ++test)
    {
        int rows, cols;
        cin >> rows >> cols;
        vector<vector<double> > a(rows, vector<double>(cols));
        for (int i = 0; i < rows; ++i)
            for (int j = 0; j < cols; ++j)
                cin >> a[i][j];

        vector<vector<double> > result(24, vector<double>(cols, 0.0));
        // J[r][k] 只会影响结果第 r 行，跳过 J 中的所有零元素。
        for (const Entry &entry : J)
            for (int j = 0; j < cols; ++j)
                result[entry.row][j] += entry.value * a[entry.col][j];

        cout << 24 << ' ' << cols << '\n';
        for (int i = 0; i < 24; ++i)
        {
            for (int j = 0; j < cols; ++j)
                cout << result[i][j] << ' ';
            cout << '\n';
        }
    }
    return 0;
}
